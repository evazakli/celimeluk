export function getWordOfDay(date = new Date()) {
  const start = new Date(2024, 0, 1);
  const diff = Math.floor((date.getTime() - start.getTime()) / (1000 * 60 * 60 * 24));
  // 2606 kelimelik listeden alfabetik ardışıklık olmadan, her gün dengeli ve deterministik seçim yapan tam döngü permütasyon
  const index = ((diff * 1013 + 37) % WORDS.length + WORDS.length) % WORDS.length;
  return { word: WORDS[index], dayNumber: diff };
}

export function isValidWord(word) {
  return WORDS.includes(word.toLocaleLowerCase('tr-TR'));
}

export function getRandomWord() {
  const index = Math.floor(Math.random() * WORDS.length);
  return WORDS[index];
}
