// Hızlı O(1) arama için tüm geçerli tahminlerin Set kümesi (Toplam 5.634 kelime)
const VALID_GUESSES_SET = new Set([...TARGET_WORDS, ...EXTRA_GUESSES]);

/**
 * Günün Kelimesi Seçimi:
 * Yalnızca kaliteli TARGET_WORDS (2.606) listesinden,
 * tam döngülü asal permütasyon ile dengeli ve deterministik olarak seçilir.
 */
export function getWordOfDay(date = new Date()) {
  const start = new Date(2024, 0, 1);
  const diff = Math.floor((date.getTime() - start.getTime()) / (1000 * 60 * 60 * 24));
  const index = ((diff * 1013 + 37) % TARGET_WORDS.length + TARGET_WORDS.length) % TARGET_WORDS.length;
  return { word: TARGET_WORDS[index], dayNumber: diff };
}

/**
 * Tahmin Doğrulama:
 * Oyuncunun yazdığı kelime, genişletilmiş tam sözlük havuzundan (5.634 kelime) kontrol edilir.
 * Böylece oyuncu nadir kelimeleri de tahmin olarak kullanabilir.
 */
export function isValidWord(word) {
  if (!word || typeof word !== 'string') return false;
  return VALID_GUESSES_SET.has(word.toLocaleLowerCase('tr-TR'));
}

/**
 * Alıştırma Modu Kelimesi:
 * Yine yalnızca kaliteli TARGET_WORDS listesinden rastgele seçilir.
 */
export function getRandomWord() {
  const index = Math.floor(Math.random() * TARGET_WORDS.length);
  return TARGET_WORDS[index];
}
